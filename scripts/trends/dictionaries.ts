/**
 * 키워드 뽑기에 쓰는 사전들. 키 없이 도는 방법의 품질은 거의 여기서 나온다.
 * 순위에 이상한 말이 올라오면 대개 STOPWORDS 에 넣으면 된다.
 * 낱말은 normalizeKey()(소문자·공백 없음) 기준으로 비교한다.
 */

/**
 * 𝐙𝐄𝐔𝐒 같은 수학 글꼴·전각 글자를 보통 글자로 바꾼다.
 * 한글 낱자(ㅋㅋ, ㅠㅠ)와 완성형은 그대로 둔다 — NFKC 는 이것들을 첫가끝 낱자로 바꿔 버린다.
 */
export function foldText(text: string): string {
  return text.replace(/[^\u3130-\u318f\uac00-\ud7a3]+/g, (part) => part.normalize("NFKC"));
}

export function normalizeKey(text: string): string {
  return foldText(text).toLowerCase().replace(/[\s·・.\-_]/g, "");
}

