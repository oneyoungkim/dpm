export function normalizeTeamKey(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

const TABLE = new Map(Object.entries(KO).map(([en, ko]) => [normalizeTeamKey(en), ko]));

/** 같은 실행에서 같은 경고를 여러 번 찍지 않는다. */
const warned = new Set<string>();

export function koreanTeamName(name: string): string {
  const trimmed = name.trim();
  const hit = TABLE.get(normalizeTeamKey(trimmed));
  if (hit) return hit;
  if (!warned.has(trimmed)) {
    warned.add(trimmed);
    console.warn(`   · 한국어 이름 없는 팀: "${trimmed}" (scripts/sources/team-names.ts 에 추가)`);
  }
  return trimmed;
}
